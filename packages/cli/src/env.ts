import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { generateKeys } from "./keys.ts";
import type { Env } from "./project.ts";
import { workdir } from "./workdir.ts";

export { workdir };

/**
 * `KEY=value` lines (dotenv syntax): `#` comments, optional `export`, single or double quotes; a
 * double-quoted value may span lines (a PEM private key), as Bun's and dotenv's loaders read it.
 */
export function parseEnv(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/.exec(lines[i] as string);
    if (!m) continue;
    let v = m[2] ?? "";
    // An open double quote: the value goes on to the line that closes it.
    if (v.startsWith('"') && !/^"(?:[^"\\]|\\.)*"/.test(v)) {
      let j = i + 1;
      while (j < lines.length && !/(?:^|[^\\])"\s*$/.test(lines[j] as string)) j++;
      if (j < lines.length) {
        v = [v, ...lines.slice(i + 1, j + 1)].join("\n").trimEnd();
        i = j;
      }
    }
    const q = v[0];
    if (q === '"' && /^"(?:[^"\\]|\\.)*"/s.test(v)) {
      v = (/^"((?:[^"\\]|\\.)*)"/s.exec(v)?.[1] ?? "").replace(/\\n/g, "\n").replace(/\\(["\\])/g, "$1");
    } else if (q === "'" && v.endsWith(q) && v.length > 1) {
      v = v.slice(1, -1);
    } else v = v.replace(/\s+#.*$/, "");
    out[m[1] as string] = v;
  }
  return out;
}

const read = (path: string) => (existsSync(path) ? parseEnv(readFileSync(path, "utf8")) : {});

/**
 * Dev keys: generated once into `.openconnect/dev.vars`, kept across runs so sealed credentials,
 * signed states and the API key stay valid. Missing ones are added, existing ones never replaced.
 */
export function devKeys(dir: string): { keys: Record<string, string>; created: boolean } {
  const path = join(workdir(dir), "dev.vars");
  const have = read(path);
  const fresh = generateKeys();
  // An existing V<n> key set means encryption keys exist; don't add a V1 next to them.
  if (Object.keys(have).some((k) => /^OPENCONNECT_KEY_V\d+$/.test(k))) for (const k of Object.keys(fresh)) if (k.startsWith("OPENCONNECT_KEY_V")) delete fresh[k];
  const missing = Object.keys(fresh).filter((k) => !have[k]);
  if (!missing.length) return { keys: have, created: false };
  const keys = { ...have, ...Object.fromEntries(missing.map((k) => [k, fresh[k] as string])) };
  writeFileSync(
    path,
    `# Generated by openconnect dev. Local only: never commit, never reuse in production.\n${Object.entries(keys)
      .map(([k, v]) => `${k}=${v}`)
      .join("\n")}\n`,
    { mode: 0o600 },
  );
  return { keys, created: true };
}

/**
 * Dev's environment, lowest to highest: generated keys, `.env` (the app's one file, trigger.dev
 * style: shared with the app), the process environment. The runtime gets only the names the project
 * reads (`workerEnv`), so the app's other vars (DATABASE_URL) never reach it.
 */
export function loadEnv(dir: string, generated: Record<string, string>, processEnv: Env = process.env): Env {
  if (existsSync(join(dir, ".dev.vars"))) throw new Error(".dev.vars isn't read any more: move its lines into .env (one file for the app and openconnect)");
  return { ...generated, ...read(join(dir, ".env")), ...processEnv };
}
