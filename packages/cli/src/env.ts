import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { type Env, generateKeys } from "./project.ts";

/** `KEY=value` lines (dotenv / `.dev.vars` syntax): `#` comments, optional `export`, single or double quotes. */
export function parseEnv(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/.exec(line);
    if (!m) continue;
    let v = m[2] ?? "";
    const q = v[0];
    if ((q === '"' || q === "'") && v.endsWith(q) && v.length > 1) {
      v = v.slice(1, -1);
      if (q === '"') v = v.replace(/\\n/g, "\n").replace(/\\(["\\])/g, "$1");
    } else v = v.replace(/\s+#.*$/, "");
    out[m[1] as string] = v;
  }
  return out;
}

const read = (path: string) => (existsSync(path) ? parseEnv(readFileSync(path, "utf8")) : {});

/** The project's local directory: generated keys, the state snapshot, builds. Ignored by git on its own. */
export function workdir(dir: string) {
  const w = join(dir, ".openconnect");
  mkdirSync(w, { recursive: true });
  if (!existsSync(join(w, ".gitignore"))) writeFileSync(join(w, ".gitignore"), "*\n");
  return w;
}

/**
 * Dev keys: generated once into `.openconnect/dev.vars`, kept across runs so sealed credentials,
 * signed states and the API key stay valid. Missing ones are added, existing ones never replaced.
 */
export function devKeys(dir: string): { keys: Record<string, string>; created: boolean } {
  const path = join(workdir(dir), "dev.vars");
  const have = read(path);
  const fresh = generateKeys();
  // An existing V<n> key set means encryption keys exist; don't add a V1 next to them.
  if (Object.keys(have).some((k) => /^OPENCONNECT_KEY_V\d+$/.test(k))) for (const k of Object.keys(fresh)) if (k.startsWith("OPENCONNECT_KEY_V")) delete fresh[k];
  const missing = Object.keys(fresh).filter((k) => !have[k]);
  if (!missing.length) return { keys: have, created: false };
  const keys = { ...have, ...Object.fromEntries(missing.map((k) => [k, fresh[k] as string])) };
  writeFileSync(
    path,
    `# Generated by openconnect dev. Local only: never commit, never reuse in production.\n${Object.entries(keys)
      .map(([k, v]) => `${k}=${v}`)
      .join("\n")}\n`,
    { mode: 0o600 },
  );
  return { keys, created: true };
}

/** Lowest to highest: generated keys, `.env`, `.dev.vars`, the process environment. */
export function loadEnv(dir: string, generated: Record<string, string>, processEnv: Env = process.env): Env {
  return { ...generated, ...read(join(dir, ".env")), ...read(join(dir, ".dev.vars")), ...processEnv };
}
