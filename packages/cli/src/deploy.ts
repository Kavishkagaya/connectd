import { existsSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, relative, resolve as resolvePath } from "node:path";
import { pathToFileURL } from "node:url";
import { parseEnv, workdir } from "./env.ts";
import { ENV, type Env, resolve, unconfiguredText } from "./project.ts";
import type { Adapter, Deployed } from "./target.ts";

/**
 * `openconnect deploy` (#31): what every target shares. The production environment (and the checks
 * that keep dev values and generated keys out of it), the project resolved against it, the secrets
 * (only the names it reads), then the target's adapter (`target: cloudflare(...)` in the config,
 * @openconnect/cloudflare) does the rest; the app's env lines close it.
 */

/** Keys only the deployment holds: generated by its adapter, never read from a file, never printed. */
const GENERATED = [ENV.state, ENV.sessions, ENV.webhooks] as const;
const ROTATABLE = { key: "encryption key (a new OPENCONNECT_KEY_V<n>)", "api-key": ENV.apiKey, state: ENV.state, sessions: ENV.sessions } as const;
/** The OPENCONNECT_ values that are the user's to set (the rest are generated, or the URL). */
const USER_SET = [ENV.events, ENV.apiKey] as const;

export type DeployOptions = {
  dir: string;
  /** The config and the entry to bundle (`loadProject`: the config plus folder discovery). */
  load: (env: import("./project.ts").Env) => Promise<{ config: import("./project.ts").Config; entry: string }>;
  name?: string;
  url?: string;
  /** The production env file. Default `.env.production`, else the shell environment; only the names the project reads (plus OPENCONNECT_EVENTS_SECRET and OPENCONNECT_API_KEY) become Worker secrets. */
  envFile?: string;
  rotate?: string[];
  dryRun?: boolean;
  /** Generate fresh runtime keys even though the index database exists without its Worker. */
  newKeys?: boolean;
  /** The target's deploy tool (Cloudflare: wrangler). Default: the adapter's own lookup. */
  wrangler?: string;
  env?: Env;
  log?: (line: string) => void;
};

export async function deploy(o: DeployOptions): Promise<Deployed> {
  const log = o.log ?? console.log;
  const env = o.env ?? process.env;
  const work = workdir(o.dir);

  // The production environment: --env-file, else .env.production, else (in CI only) the shell's:
  // a local shell holds dev's .env too (Bun loads it). Never the dev keys: the adapter generates the
  // deployment's own.
  const ci = !!env.CI && env.CI !== "false" && env.CI !== "0";
  const prod = join(o.dir, ".env.production");
  const file = o.envFile ? resolvePath(o.dir, o.envFile) : existsSync(prod) ? prod : undefined;
  const from = file ? relative(o.dir, file) : "the shell environment";
  if (file && !existsSync(file)) throw new Error(`no env file ${o.envFile}`);
  if (!file && !ci)
    throw new Error("no .env.production: put the production values there (see .env.production.example), or pass --env-file. In CI (CI=true) deploy reads the shell environment (your CI secrets) instead.");
  const devVars = join(work, "dev.vars");
  if (file === devVars) throw new Error(".openconnect/dev.vars holds dev keys; deploy generates its own. Put production values in .env.production");
  if (file === join(o.dir, ".env")) throw new Error(".env is dev's; put production values in .env.production (or the shell environment)");
  const source: Env = file ? parseEnv(readFileSync(file, "utf8")) : env;
  // Dev's values, by file: none of them may go to production (a dev OAuth app, a dev key).
  const devFiles = [devVars, ...[".env", ".env.local", ".env.development"].map((f) => join(o.dir, f))].filter((f) => existsSync(f));
  const devValues = devFiles.flatMap((f) => Object.entries(parseEnv(readFileSync(f, "utf8"))).map(([k, v]) => ({ k, v, f: relative(o.dir, f) })));
  if (file)
    for (const k of Object.keys(source)) {
      if (k === ENV.url) throw new Error(`${ENV.url} comes from --url (or the workers.dev URL), not the env file`);
      if (k.startsWith(ENV.key) || (GENERATED as readonly string[]).includes(k)) throw new Error(`${k} is generated by deploy and kept in the deployment only; remove it from ${from}`);
    }

  const { config, entry } = await o.load({ ...source });
  const project = resolve(config, { ...source });
  // Only what the project reads (and the two OPENCONNECT_ values that are yours) becomes a Worker secret.
  const secrets: Record<string, string> = {};
  for (const [k, v] of Object.entries(source)) if (v && (project.envNames.includes(k) || (USER_SET as readonly string[]).includes(k))) secrets[k] = v;
  for (const [k, v] of Object.entries(secrets)) {
    const d = devValues.find((x) => x.k === k && x.v && x.v === v);
    if (d) throw new Error(`${k} in ${from} is the dev value from ${d.f}; use a production one`);
  }
  // In CI nobody reads the log for a one-time key: it comes from a CI secret, like the app's copy.
  if (ci && !secrets[ENV.apiKey]) throw new Error(`CI: set ${ENV.apiKey} as a CI secret (\`openconnect keys\` makes one) and give your app the same value; deploy doesn't generate or print it in CI`);
  const unsent = file ? Object.keys(source).filter((k) => !Object.hasOwn(secrets, k)) : [];

  const rotate = (o.rotate ?? []).filter(Boolean);
  for (const r of rotate) {
    if (r === "webhooks") throw new Error("--rotate webhooks would break every registered webhook (#25: no key versions yet); not supported");
    if (r === "events") throw new Error(`${ENV.events} is yours: change it in .env.production (and in your app)`);
    if (!Object.hasOwn(ROTATABLE, r)) throw new Error(`--rotate takes ${Object.keys(ROTATABLE).join(", ")}`);
    if (r === "api-key" && secrets[ENV.apiKey]) throw new Error(`${ENV.apiKey} is set in ${from}; change it there (\`openconnect keys\` makes a new one)`);
  }

  const target = project.target;
  if (!target) throw new Error('deploy needs a target in oc.config.ts: `target: cloudflare({ name: "my-app" })` from @openconnect/cloudflare (bun add -d @openconnect/cloudflare)');
  const adapter = await load(o.dir, target.adapter);
  const missing = unconfiguredText(project);
  const r = await adapter.deploy({
    dir: o.dir,
    entry,
    project,
    options: target.options ?? {},
    ...(o.name ? { name: o.name } : {}),
    ...(o.url ? { url: o.url } : {}),
    secrets,
    from,
    rotate,
    dryRun: !!o.dryRun,
    newKeys: !!o.newKeys,
    ci,
    summary: [
      `  definitions  ${project.definitions.map((d) => d.id).join(", ") || "none"}`,
      ...(missing.length ? [`  no config    ${missing.join(", ")}   (not_configured until ${from} has them)`] : []),
      `  secrets      ${Object.keys(secrets).sort().join(", ") || "none"} from ${from}${rotate.length ? `, rotating ${rotate.join(", ")}` : ""}`,
      ...(unsent.length ? [`  not sent     ${unsent.join(", ")}   (nothing in the project reads them)`] : []),
    ],
    ...(o.wrangler ? { bin: o.wrangler } : {}),
    env,
    log,
  });
  if (!r.dryRun && r.url)
    log(
      [
        "",
        "your app's env (where it calls openconnect):",
        `  OPENCONNECT_URL=${r.url}`,
        r.apiKey
          ? `  ${ENV.apiKey}=${r.apiKey}   (shown once: store it now. It can't be read back; --rotate api-key makes a new one)`
          : `  ${ENV.apiKey}=${secrets[ENV.apiKey] ? `the one in ${from}` : "unchanged (the one you stored at the first deploy)"}`,
        ...(project.events ? [`  ${ENV.events}=the one in ${from}`] : []),
      ].join("\n"),
    );
  return r;
}

/** The target's adapter module, resolved from the project (where it's installed), else from the CLI. */
async function load(dir: string, id: string): Promise<Adapter> {
  let path: string;
  try {
    path = createRequire(join(dir, "package.json")).resolve(id);
  } catch {
    try {
      path = createRequire(import.meta.url).resolve(id);
    } catch {
      throw new Error(`the deploy target's adapter ${id} isn't installed: bun add -d ${id.split("/").slice(0, 2).join("/")}`);
    }
  }
  const m = (await import(pathToFileURL(path).href)) as Partial<Adapter>;
  if (typeof m.deploy !== "function") throw new Error(`${id} has no deploy(): not a deploy adapter`);
  return m as Adapter;
}
