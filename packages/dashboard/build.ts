// `bun run build`: bundles the browser UI (ui/: React + shadcn, Tailwind) into src/assets.ts, which
// the dashboard() extension serves. Committed, so the runtime needs no build step (Workers, dev,
// tests); index.test.ts fails when the sources changed since the last build.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const UI = join(import.meta.dir, "ui");
const walk = (d: string): string[] => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]));

/** Every UI file, and what shapes the output (the package's dependencies, this script). */
export const SOURCES = () => [...walk(UI).filter((f) => !/\.test\.tsx?$/.test(f)).sort(), join(import.meta.dir, "build.ts"), join(import.meta.dir, "package.json")];

/** Hash of the sources: the assets' cache-busting version, and how the test tells they're current. */
export const sourceHash = () =>
  createHash("sha256")
    .update(SOURCES().map((f) => `${f.slice(import.meta.dir.length)}\0${readFileSync(f, "utf8")}`).join("\0"))
    .digest("hex")
    .slice(0, 16);

export async function build() {
  const out = await Bun.build({
    entrypoints: [join(UI, "main.tsx")],
    target: "browser",
    format: "esm",
    minify: true,
    define: { "process.env.NODE_ENV": '"production"' },
  });
  if (!out.success) throw new AggregateError(out.logs, "dashboard build failed");
  const js = await out.outputs[0]!.text();
  const tw = spawnSync(join(import.meta.dir, "node_modules", ".bin", "tailwindcss"), ["-i", join(UI, "app.css"), "--minify"], { cwd: import.meta.dir, encoding: "utf8" });
  if (tw.status !== 0) throw new Error(`tailwindcss failed:\n${tw.stderr}`);
  return `// Generated by \`bun run build\` (build.ts) from ui/. Don't edit.
export const version = ${JSON.stringify(sourceHash())};
export const js = ${JSON.stringify(js)};
export const css = ${JSON.stringify(tw.stdout)};
`;
}

if (import.meta.main) writeFileSync(join(import.meta.dir, "src", "assets.ts"), await build());
