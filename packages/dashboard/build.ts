// `bun run build`: bundles the browser UI (src/main.ts + app.ts, src/app.css) into src/assets.ts, which
// the dashboard() extension serves. Committed, so the runtime needs no build step (Workers, dev,
// tests); assets.test.ts fails when the sources changed since the last build.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

export const SOURCES = ["src/app.ts", "src/main.ts", "src/app.css"].map((f) => `${import.meta.dir}/${f}`);

/** Hash of the sources: the assets' cache-busting version, and how the test tells they're current. */
export const sourceHash = () => createHash("sha256").update(SOURCES.map((f) => readFileSync(f, "utf8")).join("\0")).digest("hex").slice(0, 16);

export async function build() {
  const out = await Bun.build({ entrypoints: [`${import.meta.dir}/src/main.ts`], target: "browser", format: "esm", minify: true });
  if (!out.success) throw new AggregateError(out.logs, "dashboard build failed");
  const js = await out.outputs[0]!.text();
  const css = readFileSync(`${import.meta.dir}/src/app.css`, "utf8");
  return `// Generated by \`bun run build\` (build.ts) from src/app.ts, src/main.ts and src/app.css. Don't edit.
export const version = ${JSON.stringify(sourceHash())};
export const js = ${JSON.stringify(js)};
export const css = ${JSON.stringify(css)};
`;
}

if (import.meta.main) writeFileSync(`${import.meta.dir}/src/assets.ts`, await build());
