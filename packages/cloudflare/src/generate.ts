import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { ENV } from "@kavishkagaya/connectd/keys";
import { workdir } from "@kavishkagaya/connectd/workdir";

// What `connectd deploy` writes. Node APIs only and no runtime imports: the workerd test's vitest
// config (run by Node) generates the fixture's Worker with it.

export const COMPATIBILITY_DATE = "2026-09-01";
/** `CF_VERSION_METADATA`, as the platform (kernel `/do`) reads it; not imported, since that module imports cloudflare:workers. */
const VERSION_BINDING = "CF_VERSION_METADATA";
const DO_CLASS = "Connection";
const PLACEHOLDER_DB = "00000000-0000-0000-0000-000000000000";

const here = (f: string) => fileURLToPath(new URL(f, import.meta.url));
const own = createRequire(import.meta.url);

/**
 * The package the user's project resolves (the copy its config's definitions are bundled with), else
 * this package's. The runtime comes with @kavishkagaya/connectd, a peer dependency, so it's one copy in
 * an installed project and `instanceof` holds across the bundle.
 */
function fromProject(dir: string, id: string) {
  try {
    return createRequire(join(dir, "package.json")).resolve(id);
  } catch {
    return own.resolve(id);
  }
}

/** Worker names: lowercase letters, digits and dashes. */
export const workerName = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 54) || "connectd";

/** `--url` / `cloudflare({ url })`: https, served at the root (routes are keyed by the first path segment). */
export function publicUrl(u: string) {
  let url: URL;
  try {
    url = new URL(u);
  } catch {
    throw new Error(`--url ${u} is not a URL`);
  }
  if (url.protocol !== "https:") throw new Error(`--url must be https (${u})`);
  if (url.pathname !== "/" || url.search || url.hash) throw new Error(`--url must be an origin, served at its root (${u}): the runtime routes by the first path segment`);
  return url.origin;
}

export type Generated = { dir: string; entry: string; wrangler: string; migrations: string };

/**
 * Write the Worker entry, the wrangler config and the index migrations into `<dir>/.connectd/deploy`.
 * Node APIs only (the workerd test's vitest config runs it under Node).
 */
export function generate(o: { dir: string; config: string; name: string; url?: string; databaseId?: string }): Generated {
  const out = join(workdir(o.dir), "deploy");
  mkdirSync(out, { recursive: true });
  const rel = (p: string) => {
    const r = relative(out, p).split(sep).join("/");
    return JSON.stringify(r.startsWith(".") ? r : `./${r}`);
  };

  // The template's imports, pointed at the user's config and the runtime and CLI the project resolves.
  const entry = join(out, "worker.ts");
  const runtimeIndex = fromProject(o.dir, "@kavishkagaya/connectd/runtime");
  const src = readFileSync(here("./worker.ts"), "utf8")
    .replace('"@kavishkagaya/connectd/runtime/cloudflare"', rel(fromProject(o.dir, "@kavishkagaya/connectd/runtime/cloudflare")))
    .replace('"@kavishkagaya/connectd/runtime"', rel(runtimeIndex))
    .replace('"connectd:config"', rel(o.config))
    .replace('"@kavishkagaya/connectd"', rel(fromProject(o.dir, "@kavishkagaya/connectd")));
  writeFileSync(entry, `// Generated by connectd deploy, rebuilt on every deploy: edit src/worker.ts in @kavishkagaya/connectd-cloudflare instead.\n${src}`);

  // The management database's schema ships with the Cloudflare platform (kernel `/do`), next to its
  // code: <kernel>/migrations in the published @kavishkagaya/connectd (<kernel>/dist/drivers/do.js).
  // In this repo the import is the CLI's re-export, so the workspace package's. Copied so wrangler
  // finds it next to its config.
  const migrations = join(out, "migrations");
  rmSync(migrations, { recursive: true, force: true });
  mkdirSync(migrations);
  const beside = join(dirname(fromProject(o.dir, "@kavishkagaya/connectd/kernel/do")), "..", "..", "migrations");
  const from = existsSync(beside) ? beside : join(dirname(own.resolve("@kavishkagaya/connectd-kernel/do")), "..", "..", "migrations");
  for (const f of readdirSync(from)) if (f.endsWith(".sql")) copyFileSync(join(from, f), join(migrations, f));

  const custom = o.url && !new URL(o.url).hostname.endsWith(".workers.dev") ? new URL(o.url).hostname : undefined;
  const config = {
    name: o.name,
    main: "worker.ts",
    compatibility_date: COMPATIBILITY_DATE,
    workers_dev: !custom,
    ...(custom ? { routes: [{ pattern: custom, custom_domain: true }] } : {}),
    // Not a secret: the callback and webhook URLs are public.
    vars: o.url ? { [ENV.url]: o.url } : {},
    // `platform.version`: the deployed version's id.
    version_metadata: { binding: VERSION_BINDING },
    durable_objects: { bindings: [{ name: "CONNECTION", class_name: DO_CLASS }] },
    migrations: [{ tag: "v1", new_sqlite_classes: [DO_CLASS] }],
    d1_databases: [{ binding: "INDEX", database_name: `${o.name}-index`, database_id: o.databaseId ?? PLACEHOLDER_DB, migrations_dir: "migrations" }],
  };
  const wrangler = join(out, "wrangler.json");
  writeFileSync(wrangler, `${JSON.stringify(config, null, 2)}\n`);
  return { dir: out, entry, wrangler, migrations };
}
